"""## 0.1 Tải model và audio tokenizer (BiCodec)"""

import sys, re, torch, numpy as np
from unsloth import FastModel
from huggingface_hub import snapshot_download
from IPython.display import Audio, display

# Tải toàn bộ Spark-TTS (gồm phần LLM + BiCodec)
snapshot_download("unsloth/Spark-TTS-0.5B", local_dir="Spark-TTS-0.5B")

max_seq_length = 2048
model, tokenizer = FastModel.from_pretrained(
    model_name="Spark-TTS-0.5B/LLM",
    max_seq_length=max_seq_length,
    dtype=torch.float32,   # Spark hiện chỉ chạy ổn với float32
    full_finetuning=False,
    load_in_4bit=False,
)

# Audio tokenizer: chuyển audio <-> token
sys.path.append("Spark-TTS")
from sparktts.models.audio_tokenizer import BiCodecTokenizer
from sparktts.utils.audio import audio_volume_normalize
audio_tokenizer = BiCodecTokenizer("Spark-TTS-0.5B", "cuda")
SAMPLE_RATE = audio_tokenizer.config["sample_rate"]  # 16000
print("Sample rate:", SAMPLE_RATE)

"""## 0.2 Hàm sinh giọng nói"""

@torch.inference_mode()
def generate_speech(text, mode="tts", temperature=0.8, top_k=50, top_p=1.0,
                    max_new_audio_tokens=2048, gender="female"):
    """
    mode="controllable": prompt chuẩn của Spark-TTS gốc (chọn giới tính, cao độ, tốc độ)
                         -> dùng để test model GỐC cho công bằng.
    mode="tts":          prompt giống lúc fine-tune -> dùng cho model ĐÃ FINE-TUNE.
    """
    torch.compiler.reset()
    if mode == "controllable":
        gender_id = {"female": 0, "male": 1}[gender]
        prompt = "".join([
            "<|task_controllable_tts|>", "<|start_content|>", text, "<|end_content|>",
            "<|start_style_label|>", f"<|gender_{gender_id}|>",
            "<|pitch_label_2|>", "<|speed_label_2|>", "<|end_style_label|>",
        ])
    else:
        prompt = "".join([
            "<|task_tts|>", "<|start_content|>", text, "<|end_content|>",
            "<|start_global_token|>",
        ])

    inputs = tokenizer([prompt], return_tensors="pt").to("cuda")
    out = model.generate(
        **inputs, max_new_tokens=max_new_audio_tokens, do_sample=True,
        temperature=temperature, top_k=top_k, top_p=top_p,
        eos_token_id=tokenizer.eos_token_id, pad_token_id=tokenizer.pad_token_id,
    )
    pred = tokenizer.batch_decode(out[:, inputs.input_ids.shape[1]:], skip_special_tokens=False)[0]

    semantic = re.findall(r"<\|bicodec_semantic_(\d+)\|>", pred)
    if not semantic:
        print("Cảnh báo: model không sinh ra semantic token nào.")
        return np.zeros(SAMPLE_RATE // 2, dtype=np.float32)
    semantic_ids = torch.tensor([int(t) for t in semantic]).long().unsqueeze(0)

    glob = re.findall(r"<\|bicodec_global_(\d+)\|>", pred)
    global_ids = (torch.tensor([int(t) for t in glob]).long().unsqueeze(0)
                  if glob else torch.zeros((1, 1), dtype=torch.long))

    audio_tokenizer.device = "cuda"
    audio_tokenizer.model.to("cuda")
    wav = audio_tokenizer.detokenize(global_ids.to("cuda"), semantic_ids.to("cuda"))
    return np.asarray(wav, dtype=np.float32)

"""## 1. Chạy thử tiếng Việt trên model GỐC
Model gốc chủ yếu được train tiếng Anh + tiếng Trung, nên dự kiến phát âm tiếng Việt sẽ sai nhiều.
"""

FastModel.for_inference(model)

# Thử nhanh 1 câu với model gốc
text = "Chào mừng các bạn đến với kênh Mì AI, học AI theo cách mì ăn liền."
display(Audio(generate_speech(text, mode="controllable"), rate=SAMPLE_RATE))

"""## 2. Fine-tune bằng `doof-ferb/infore1_25hours`

### 2.1 Tải và lọc dữ liệu
"""

from datasets import load_dataset, Audio as HFAudio

NUM_SAMPLES = 2000        # số mẫu dùng để train (tăng lên nếu có thời gian)
MAX_SECONDS = 15          # bỏ clip quá dài

ds = load_dataset("doof-ferb/infore1_25hours", split="train")
ds = ds.rename_column("transcription", "text")
ds = ds.shuffle(seed=42).select(range(min(NUM_SAMPLES * 2, len(ds))))
ds = ds.cast_column("audio", HFAudio(sampling_rate=SAMPLE_RATE))
ds = ds.filter(
    lambda x: x["text"] is not None and len(x["text"].strip()) > 0
              and len(x["audio"]["array"]) <= MAX_SECONDS * SAMPLE_RATE,
    desc="Lọc dữ liệu",
)
ds = ds.select(range(min(NUM_SAMPLES, len(ds))))
print(ds)
print("Ví dụ:", ds[0]["text"])

"""### 2.2 Chuyển audio thành token BiCodec (định dạng train của Spark-TTS)"""

def extract_wav2vec2_features(wavs):
    wav_np = wavs.squeeze(0).cpu().numpy()
    processed = audio_tokenizer.processor(wav_np, sampling_rate=16000,
                                          return_tensors="pt", padding=True)
    input_values = processed.input_values.to(audio_tokenizer.feature_extractor.device)
    out = audio_tokenizer.feature_extractor(input_values)
    hs = out.hidden_states
    return (hs[11] + hs[14] + hs[16]) / 3

@torch.no_grad()
def format_example(example):
    audio_array = np.asarray(example["audio"]["array"], dtype=np.float32)
    if audio_tokenizer.config["volume_normalize"]:
        audio_array = audio_volume_normalize(audio_array)
    ref_wav = audio_tokenizer.get_ref_clip(audio_array)

    wav_t = torch.from_numpy(audio_array).unsqueeze(0).float().to(audio_tokenizer.device)
    ref_t = torch.from_numpy(ref_wav).unsqueeze(0).float().to(audio_tokenizer.device)
    feat = extract_wav2vec2_features(wav_t)

    semantic_ids, global_ids = audio_tokenizer.model.tokenize(
        {"wav": wav_t, "ref_wav": ref_t, "feat": feat.to(audio_tokenizer.device)}
    )
    global_tokens = "".join(f"<|bicodec_global_{i}|>" for i in global_ids.squeeze().cpu().numpy())
    semantic_tokens = "".join(f"<|bicodec_semantic_{i}|>" for i in semantic_ids.squeeze().cpu().numpy())

    text = "".join([
        "<|task_tts|>", "<|start_content|>", example["text"], "<|end_content|>",
        "<|start_global_token|>", global_tokens, "<|end_global_token|>",
        "<|start_semantic_token|>", semantic_tokens, "<|end_semantic_token|>",
        "<|im_end|>",
    ])
    return {"text": text}

train_ds = ds.map(format_example, remove_columns=ds.column_names, desc="Tokenize audio")

# Giải phóng GPU cho lúc train
audio_tokenizer.model.cpu()
audio_tokenizer.feature_extractor.cpu()
torch.cuda.empty_cache()
print(train_ds[0]["text"][:300], "...")

"""### 2.3 Gắn LoRA và train"""

model = FastModel.get_peft_model(
    model,
    r=128,
    target_modules=["q_proj", "k_proj", "v_proj", "o_proj",
                    "gate_proj", "up_proj", "down_proj"],
    lora_alpha=128,
    lora_dropout=0,
    bias="none",
    use_gradient_checkpointing="unsloth",
    random_state=3407,
)
FastModel.for_training(model)

from trl import SFTConfig, SFTTrainer

trainer = SFTTrainer(
    model=model,
    tokenizer=tokenizer,
    train_dataset=train_ds,
    dataset_text_field="text",
    max_seq_length=max_seq_length,
    packing=False,
    args=SFTConfig(
        per_device_train_batch_size=8, # Nhỏ thì về 2
        gradient_accumulation_steps=1, # Nhỏ thì lên 4
        warmup_steps=10,
        num_train_epochs=5,      # 2000 mẫu x 2 epoch ~ 1250 bước. Học ngôn ngữ mới cần nhiều bước
        learning_rate=2e-4,
        fp16=False, bf16=False,  # Spark train ở float32
        logging_steps=10,
        optim="adamw_8bit",
        weight_decay=0.01,
        lr_scheduler_type="linear",
        seed=3407,
        output_dir="outputs",
        report_to="none",
    ),
)
stats = trainer.train()
print(f"Thời gian train: {stats.metrics['train_runtime']/60:.1f} phút")

"""## 3. Chạy lại sau fine-tune và so sánh
Dùng đúng các câu test ở phần 1.
"""

FastModel.for_inference(model)

# Cùng câu đã thử ở phần 1
